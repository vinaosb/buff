// Rust: hello world. Even the simplest program shows friction:
//   - println! is a MACRO (note the `!`), not a regular function.
//   - Every statement ends with `;`.
//   - The body of main requires `{ }` braces.
//   - Functions are declared with `fn`, not `func`.
//   - String literals are &str (borrowed slices), not owned String.

fn main() {
    println!("Hello, Buff!");
}
