#[test]
fn scan_with_detail_returns_advisory_hit_struct() {
    let tmp = std::env::temp_dir().join(format!(
        "buff-audit-test-detail-{}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&tmp);
    std::fs::create_dir_all(&tmp).expect("mkdir");
    let cargo_lock = tmp.join("Cargo.lock");
    std::fs::write(
        &cargo_lock,
        r#"[[package]]
name = "chrono"
version = "0.4.19"
"#,
    )
    .expect("write Cargo.lock");
    let hits = scan_with_detail(&tmp).expect("scan_with_detail");
    assert_eq!(hits.len(), 1);
    let expected = AdvisoryHit {
        id: "RUSTSEC-2020-0159".to_string(),
        package: "chrono".to_string(),
        patched: "0.4.20".to_string(),
    };
    assert_eq!(hits[0], expected);
    let _ = std::fs::remove_dir_all(&tmp);
}

#[test]
fn keypair_returns_two_distinct_64char_hex_strings() {
    let (pk, sk) = keypair().expect("keypair");
    assert_eq!(pk.len(), 64);
    assert_eq!(sk.len(), 64);
    assert_ne!(pk, sk, "public != secret");
    let (pk2, _) = keypair().expect("keypair 2");
    assert_ne!(
        pk, pk2,
        "two CSPRNG keypairs should differ (with overwhelming probability)"
    );
}

#[test]
fn sign_rejects_short_secret_key_with_bad_key_error() {
    let err = sign(b"data", "abcd").unwrap_err();
    assert!(matches!(err, AuditError::BadKey(_)));
}

#[test]
fn sign_rejects_invalid_hex_secret_with_hex_error() {
    let err = sign(b"data", "ZZ").unwrap_err();
    assert!(matches!(err, AuditError::Hex(_)));
}

#[test]
fn verify_rejects_short_public_key_with_bad_key_error() {
    let sig = "00".repeat(64);
    let err = verify(b"data", &sig, "abcd").unwrap_err();
    assert!(matches!(err, AuditError::BadKey(_)));
}

#[test]
fn verify_rejects_short_signature_with_bad_signature_error() {
    let (pk, _) = keypair().expect("keypair");
    let err = verify(b"data", "abcd", &pk).unwrap_err();
    assert!(matches!(err, AuditError::BadSignature(_)));
}

#[test]
fn advisory_hit_eq_hash_derive_works() {
    let a = AdvisoryHit {
        id: "X".to_string(),
        package: "p".to_string(),
        patched: "1".to_string(),
    };
    let b = a.clone();
    assert_eq!(a, b);
    let set: std::collections::HashSet<AdvisoryHit> = [a].into_iter().collect();
    assert_eq!(set.len(), 1);
}
