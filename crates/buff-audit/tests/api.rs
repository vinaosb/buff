//! Integration tests for the `buff-audit` crate — public API surface.
//!
//! Covers every public fn per the T26 spec:
//! - `keypair()` — fresh Ed25519 CSPRNG keypair.
//! - `sign(data, secret_hex)` — detached signature.
//! - `verify(data, sig_hex, public_hex)` — strict verify, returns Bool.
//! - `scan(project_root)` — manifest substring scan.
//! - `scan_with_detail(project_root)` — same but with remediation hints.
//! - `known_advisories()` — static DB enumeration.
//!
//! Pure-Rust; no network; deterministic advisory DB.

use buff_audit::{keypair, known_advisories, scan, scan_with_detail, sign, verify, AdvisoryHit,
    AuditError, MANIFEST_PATHS};

#[test]
fn manifest_paths_priority_chain_lists_buff_lock_first() {
    assert_eq!(MANIFEST_PATHS[0], "buff.lock");
    assert_eq!(MANIFEST_PATHS[1], "Cargo.lock");
    assert_eq!(MANIFEST_PATHS[2], "buff.toml");
}

#[test]
fn known_advisories_returns_seed_entries() {
    let list = known_advisories();
    assert!(!list.is_empty(), "DB should seed with at least 1 entry");
    assert!(list.contains(&"RUSTSEC-2020-0159".to_string()));
}

#[test]
fn scan_returns_empty_when_no_manifest_exists() {
    let tmp = std::env::temp_dir().join(format!(
        "buff-audit-test-empty-{}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&tmp);
    std::fs::create_dir_all(&tmp).expect("mkdir");
    let hits = scan(&tmp).expect("scan on empty dir");
    assert!(hits.is_empty(), "empty project should have 0 advisories");
    let _ = std::fs::remove_dir_all(&tmp);
}

#[test]
fn scan_finds_vulnerable_chrono_in_cargo_lock() {
    let tmp = std::env::temp_dir().join(format!(
        "buff-audit-test-vuln-cargo-{}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&tmp);
    std::fs::create_dir_all(&tmp).expect("mkdir");
    let cargo_lock = tmp.join("Cargo.lock");
    std::fs::write(
        &cargo_lock,
        r#"# This file is automatically @generated by Cargo.
[[package]]
name = "chrono"
version = "0.4.19"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "1e37c4b6c7c7c7c7c7c7c7c7c7c7c7c7c7c7c7c"
"#,
    )
    .expect("write Cargo.lock");
    let hits = scan(&tmp).expect("scan");
    assert!(
        hits.contains(&"RUSTSEC-2020-0159".to_string()),
        "should fire on chrono 0.4.19"
    );
    let _ = std::fs::remove_dir_all(&tmp);
}

