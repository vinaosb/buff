//! `buff-mock` — Mocking framework for the Buff language.
//!
//! Provides `Mock<Trait>` — a generic mock instance with `expect` /
//! `verify` / `spy` semantics — plus a codegen-time helper
//! [`lower_mock_for_trait`] that emits the trait impl as `syn::Item`s.
//!
//! # Why this exists
//!
//! Every major language ecosystem has a mocking framework (Rust:
//! [`mockall`](https://docs.rs/mockall/), Python: `unittest.mock`,
//! C#: Moq). T22 (API compatibility spike) and T23 (flagship tests)
//! both need mock-based testing. This crate is the foundational layer
//! for both.
//!
//! # Design (per T3 macro spike DEFER outcome)
//!
//! Rust has no way to auto-derive an arbitrary trait impl without
//! procedural macros. The T3 spike deferred the macro system
//! (`.sisyphus/decisions/macro-system-v1x.md`) and recommended runtime
//! workarounds. `buff-mock` follows that recommendation:
//!
//! 1. The **runtime API** (`Mock`, `ExpectationBuilder`, `SpyHandle`)
//!    is a pure-Rust library usable directly from any test.
//! 2. The **codegen helper** [`lower_mock_for_trait`] emits the
//!    trait impl as a `syn::Item` — `buff-lang-codegen-rust` can call
//!    it in the future to expand `@mock let m: T = Mock.new()` into
//!    the right `impl T for Mock<T>` block. (Future integration; the
//!    MVP ships WITHOUT requiring parser/AST/codegen-rust changes.)
//!
//! # Quick start
//!
//! ```ignore
//! use buff_mock::{Mock, ReturnValue};
//!
//! // User-defined trait:
//! trait Greeter { fn greet(&self, name: String) -> String; }
//!
//! // User-written mock impl (or generated by `lower_mock_for_trait`):
//! impl Greeter for Mock<dyn Greeter> {
//!     fn greet(&self, name: String) -> String {
//!         self.record_call("greet", vec![buff_mock::ArgumentValue::String(name)]);
//!         match self.lookup_return("greet", &[]) {
//!             Some(ReturnValue::String(s)) => s,
//!             _ => String::new(),
//!         }
//!     }
//! }
//!
//! // Test:
//! let mock = Mock::<dyn Greeter>::new();
//! mock.expect("greet").returning(ReturnValue::String("hello".into()));
//! assert_eq!(mock.greet("alice".into()), "hello");
//! mock.verify().unwrap();
//! ```
//!
//! # Spy pattern
//!
//! ```ignore
//! let spy = mock.spy("greet");
//! mock.greet("alice".into());
//! mock.greet("bob".into());
//! assert_eq!(spy.call_count(), 2);
//! assert_eq!(spy.args()[0][0], ArgumentValue::String("alice".into()));
//! ```
//!
//! # References
//!
//! - Plan: `.sisyphus/plans/buff-v1x-frameworks.md` task T25 (lines 780-855).
//! - Macro spike decision: `.sisyphus/decisions/macro-system-v1x.md`.
//! - `mockall` (Rust): <https://docs.rs/mockall/latest/mockall/>.
//! - `unittest.mock` (Python): <https://docs.python.org/3/library/unittest.mock.html>.

