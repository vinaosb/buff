#[cfg(test)]
mod smoke_tests {
    //! Smoke tests at the crate root — assert that the public API
    //! surface compiles and the basic shape works. Full behavioral
    //! coverage lives in `tests/mock_tests.rs`.

    use super::*;

    trait SampleTrait {
        fn ping(&self) -> bool;
    }

    impl SampleTrait for Mock<dyn SampleTrait> {
        fn ping(&self) -> bool {
            self.record_call_no_args("ping");
            match self.lookup_return_no_args("ping") {
                Some(ReturnValue::Bool(b)) => b,
                _ => false,
            }
        }
    }

    #[test]
    fn smoke_mock_constructs_and_returns_default() {
        let m = Mock::<dyn SampleTrait>::new();
        assert!(!m.ping());
        assert_eq!(m.call_count_for("ping"), 1);
    }

    #[test]
    fn smoke_expect_returning_overrides_default() {
        let m = Mock::<dyn SampleTrait>::new();
        m.expect("ping").returning(ReturnValue::Bool(true));
        assert!(m.ping());
    }

    #[test]
    fn smoke_verify_passes_when_times_satisfied() {
        let m = Mock::<dyn SampleTrait>::new();
        m.expect("ping").times(1);
        let _ = m.ping();
        assert!(m.verify().is_ok());
    }

    #[test]
    fn smoke_spy_records_args() {
        trait Greeter {
            fn greet(&self, name: String) -> String;
        }
        impl Greeter for Mock<dyn Greeter> {
            fn greet(&self, name: String) -> String {
                self.record_call(
                    "greet",
                    vec![ArgumentValue::String(name)],
                );
                match self.lookup_return("greet", &[]) {
                    Some(ReturnValue::String(s)) => s,
                    _ => String::new(),
                }
            }
        }
        let m = Mock::<dyn Greeter>::new();
        let spy = m.spy("greet");
        let _ = m.greet("alice".into());
        let _ = m.greet("bob".into());
        assert_eq!(spy.call_count(), 2);
        assert_eq!(
            spy.calls().first().map(|r| r.args.clone()),
            Some(vec![ArgumentValue::String("alice".into())])
        );
    }
}
