/// `src/lib.buff` library template (T112 `--lib`).
///
/// Exports two starter functions (`greet`, `add`) with no `func main()` — a
/// library is consumed via `import { greet } from "./name"`, not run directly.
pub const LIB_BUFF_TEMPLATE: &str = r#"// {name} - generated by `buff new --lib`
// Library module. Exported functions are importable by other Buff programs:
//     import { greet } from "./{name}"

export func greet(name):
    print("Hello, " + name + "!")

export func add(a, b):
    return a + b
"#;

/// `src/main.buff` async server template (T112 `--server`).
///
/// Demonstrates the Buff async-without-`await` model: `async func` seeds the
/// call-graph propagation, `spawn` schedules a task, and `.result()` joins.
/// Running requires the Buff `tokio` runtime (v1.0); the file is a starter
/// in v0.5.
pub const SERVER_MAIN_BUFF_TEMPLATE: &str = r#"// {name} - generated by `buff new --server`
// Async server template. Running requires the Buff tokio runtime (v1.0).
// There is NO `await` keyword in Buff — async propagates up the call graph
// automatically, and `.result()` joins a spawned task.

async func handler():
    return "Hello from {name}!"

func main():
    let task = spawn handler()
    let message = task.result()
    print(message)
"#;

/// `src/main.buff` GPU-dispatch template (T112 `--gpu`).
///
/// Carries an `@prefer(gpu)` hint on a compute-style function. Real GPU
/// dispatch (WGSL shader emission + `wgpu` host) arrives in v1.0; the
/// function falls back to CPU automatically when no GPU is present.
pub const GPU_MAIN_BUFF_TEMPLATE: &str = r#"// {name} - generated by `buff new --gpu`
// GPU dispatch template. `@prefer(gpu)` hints the compiler to dispatch the
// annotated function on the GPU when hardware is available (v1.0 runtime).
// When no GPU is present the function runs on CPU — the hint never breaks.

@prefer(gpu)
func compute(a, b):
    return a * b

func main():
    let result = compute(21, 2)
    print(result)
"#;

/// Workspace-root `buff.toml` template (T112 `--workspace`).
///
/// Mirrors Cargo's `[workspace]` manifest shape: a workspace-level manifest
/// lists member crates under `crates/`. The Buff workspace resolver itself
/// is a v1.0 concern; the scaffold produces a structurally-correct starter.
pub const WORKSPACE_BUFF_TOML_TEMPLATE: &str = r#"[workspace]
name = "{name}"
version = "0.1.0"
edition = "0.1"
members = ["crates/core", "crates/utils"]
"#;

/// Workspace member `core/src/main.buff` template — binary crate entry point.
pub const WORKSPACE_CORE_MAIN_BUFF_TEMPLATE: &str = r#"// {name} workspace - core crate entry point
func main():
    print("Hello from {name} core!")
"#;

/// Workspace member `utils/src/lib.buff` template — library crate.
pub const WORKSPACE_UTILS_LIB_BUFF_TEMPLATE: &str = r#"// {name} workspace - utils crate library
export func helper():
    print("utils helper called")
"#;

/// Workspace member `buff.toml` template (shared by `core` and `utils`).
pub const WORKSPACE_MEMBER_BUFF_TOML_TEMPLATE: &str = r#"[package]
name = "{name}"
version = "0.1.0"
edition = "0.1"
"#;

/// A single scaffolded file: a path relative to the project root and the
/// already-rendered content to write at that path.
pub type ScaffoldFile = (&'static str, String);

/// Returns the set of files to write for the given `template` + project `name`.
///
/// Paths are relative to the project root (e.g. `"src/main.buff"`). The
/// caller ([`crate::commands::new::run`]) is responsible for creating parent
/// directories and refusing to clobber an existing project directory.
///
/// Every template emits a root manifest (`buff.toml`), `.gitignore`, and
/// `README.md`; the template-specific files differ.
pub fn files_for_template(template: TemplateKind, name: &str) -> Vec<ScaffoldFile> {
    let render = |t: &str| render_template(t, name);
    let mut files: Vec<ScaffoldFile> = Vec::new();

    // Root manifest: Workspace gets a [workspace] table; everyone else the
    // standard [package] manifest.
    let root_toml = match template {
        TemplateKind::Workspace => WORKSPACE_BUFF_TOML_TEMPLATE,
        _ => BUFF_TOML_TEMPLATE,
    };
    files.push(("buff.toml", render(root_toml)));
    files.push((".gitignore", GITIGNORE_TEMPLATE.to_string()));
    files.push(("README.md", render(README_TEMPLATE)));

    match template {
        TemplateKind::Binary => {
            files.push(("src/main.buff", render(MAIN_BUFF_TEMPLATE)));
        }
        TemplateKind::Lib => {
            files.push(("src/lib.buff", render(LIB_BUFF_TEMPLATE)));
        }
        TemplateKind::Server => {
            files.push(("src/main.buff", render(SERVER_MAIN_BUFF_TEMPLATE)));
        }
        TemplateKind::Gpu => {
            files.push(("src/main.buff", render(GPU_MAIN_BUFF_TEMPLATE)));
        }
        TemplateKind::Workspace => {
            files.push((
                "crates/core/buff.toml",
                render(WORKSPACE_MEMBER_BUFF_TOML_TEMPLATE),
            ));
            files.push((
                "crates/core/src/main.buff",
                render(WORKSPACE_CORE_MAIN_BUFF_TEMPLATE),
            ));
            files.push((
                "crates/utils/buff.toml",
                render(WORKSPACE_MEMBER_BUFF_TOML_TEMPLATE),
            ));
            files.push((
                "crates/utils/src/lib.buff",
                render(WORKSPACE_UTILS_LIB_BUFF_TEMPLATE),
            ));
        }
    }

    files
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_template_replaces_single_occurrence() {
        let rendered = render_template(BUFF_TOML_TEMPLATE, "my_app");
        assert!(rendered.contains("name = \"my_app\""));
        assert!(!rendered.contains("{name}"));
    }

    #[test]
    fn render_template_replaces_multiple_occurrences() {
        let rendered = render_template(README_TEMPLATE, "demo");
        // README references the name twice: header + (potentially) usage.
        assert!(rendered.matches("demo").count() >= 1);
        assert!(!rendered.contains("{name}"));
    }

    #[test]
    fn keywords_table_has_25_entries() {
        // Mirrors the lexer keyword count; if either side changes the other
        // must follow.
        assert_eq!(KEYWORDS.len(), 25, "Buff has 25 reserved keywords");
    }

    #[test]
    fn template_from_flags_defaults_to_binary() {
        assert_eq!(
            template_from_flags(false, false, false, false).unwrap(),
            TemplateKind::Binary
        );
    }

    #[test]
    fn template_from_flags_each_variant() {
        assert_eq!(
            template_from_flags(true, false, false, false).unwrap(),
            TemplateKind::Lib
        );
        assert_eq!(
            template_from_flags(false, true, false, false).unwrap(),
            TemplateKind::Server
        );
        assert_eq!(
            template_from_flags(false, false, true, false).unwrap(),
            TemplateKind::Gpu
        );
        assert_eq!(
            template_from_flags(false, false, false, true).unwrap(),
            TemplateKind::Workspace
        );
    }

    #[test]
    fn template_from_flags_rejects_multiple_set() {
        assert!(template_from_flags(true, true, false, false).is_err());
        assert!(template_from_flags(false, true, true, false).is_err());
        assert!(template_from_flags(true, false, false, true).is_err());
    }

    #[test]
    fn files_for_binary_matches_v01_layout() {
        let files = files_for_template(TemplateKind::Binary, "demo");
        let paths: Vec<_> = files.iter().map(|(p, _)| *p).collect();
        assert!(paths.contains(&"buff.toml"));
        assert!(paths.contains(&"src/main.buff"));
        assert!(paths.contains(&".gitignore"));
        assert!(paths.contains(&"README.md"));
        assert!(!paths.contains(&"src/lib.buff"));
    }

    #[test]
    fn files_for_lib_has_no_main() {
        let files = files_for_template(TemplateKind::Lib, "demo");
        let paths: Vec<_> = files.iter().map(|(p, _)| *p).collect();
        assert!(paths.contains(&"src/lib.buff"));
        assert!(!paths.contains(&"src/main.buff"));
    }

    #[test]
    fn files_for_workspace_has_member_layout() {
        let files = files_for_template(TemplateKind::Workspace, "demo");
        let paths: Vec<_> = files.iter().map(|(p, _)| *p).collect();
        assert!(paths.contains(&"crates/core/buff.toml"));
        assert!(paths.contains(&"crates/core/src/main.buff"));
        assert!(paths.contains(&"crates/utils/buff.toml"));
        assert!(paths.contains(&"crates/utils/src/lib.buff"));
    }
}
