//! Project scaffolding — templates and validation shared by `buff new` and
//! `buff init`.
//!
//! Templates are plain strings with a single `{name}` placeholder substituted
//! by [`render_template`]. They are deliberately simple (no TPL engine dep):
//! the v0.1 generated project is four small files, and a `str::replace` call
//! keeps the dependency surface minimal.
//!
//! [`validate_project_name`] enforces the same identifier rules the lexer will
//! later apply to symbols, plus a check against the 25 reserved keywords (see
//! `crates/buff-lang-lexer/src/token.rs`).

/// Reserved Buff keywords (must match the lexer's keyword table).
///
/// Sourcing this as a static array here (instead of importing from the lexer)
/// keeps `buff new` / `buff init` decoupled from lexer internals — the keyword
/// list is small and stable for v0.1.
pub const KEYWORDS: &[&str] = &[
    "func", "let", "mut", "struct", "enum", "trait", "type", "if", "else", "for", "return",
    "break", "continue", "in", "match", "async", "spawn", "import", "export", "from", "as", "true",
    "false", "extern", "unsafe",
];

/// `buff.toml` manifest template.
///
/// `{name}` is replaced with the project name. The `edition` field tracks the
/// Buff language edition (semver-ish); v0.1 emits `"0.1"`.
pub const BUFF_TOML_TEMPLATE: &str = r#"[package]
name = "{name}"
version = "0.1.0"
edition = "0.1"
"#;

/// `src/main.buff` entry-point template.
///
/// `{name}` is referenced in a leading comment. The body is the canonical v0.1
/// "Hello, Buff!" program and is runnable via `buff run src/main.buff`.
pub const MAIN_BUFF_TEMPLATE: &str = r#"// {name} - generated by `buff new`
func main():
    print("Hello, Buff!")
"#;

/// `.gitignore` template emitted into the project root.
///
/// Ignores the cargo `target/` tree, the per-project `buff.lock`, and any
/// stray generated `.rs` files (the transpiler writes them next to the source
/// — keeping them out of VCS is the user's signal that they're build artifacts).
pub const GITIGNORE_TEMPLATE: &str = r#"target/
buff.lock
*.rs
"#;

/// `README.md` template — minimal usage instructions referencing `buff run`.
pub const README_TEMPLATE: &str = r#"# {name}

Generated by `buff new`.

## Run

```
buff run src/main.buff
```
"#;

/// Validate a project name.
///
/// Rules:
/// - Non-empty.
/// - Starts with an ASCII letter or underscore (not a digit, not unicode).
/// - Subsequent characters are ASCII alphanumeric or underscore.
/// - Not a reserved Buff keyword (see [`KEYWORDS`]).
///
/// # Errors
///
/// Returns a human-readable `String` describing the first violated rule. The
/// message is suitable for direct display to the user via `anyhow::Error::msg`.
pub fn validate_project_name(name: &str) -> Result<(), String> {
    if name.is_empty() {
        return Err("project name cannot be empty".to_string());
    }
    let first = name.chars().next().expect("checked non-empty above");
    if !first.is_ascii_alphabetic() && first != '_' {
        return Err(format!(
            "project name must start with a letter or underscore: `{name}`"
        ));
    }
    if !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
        return Err(format!(
            "project name contains invalid characters (allowed: a-z, A-Z, 0-9, _): `{name}`"
        ));
    }
    if KEYWORDS.contains(&name) {
        return Err(format!(
            "invalid project name: `{name}` is a reserved Buff keyword"
        ));
    }
    Ok(())
}

/// Substitute the `{name}` placeholder in a template string.
///
/// Uses plain `str::replace`, which replaces *all* occurrences (templates may
/// reference the name multiple times, e.g. the README header and run command).
pub fn render_template(template: &str, name: &str) -> String {
    template.replace("{name}", name)
}

// ===========================================================================
// Template kinds (T112) — `buff new --{lib,server,gpu,workspace}`
// ===========================================================================

/// The kind of project to scaffold via `buff new` / `buff init` (T112).
///
/// Each variant selects a different starter layout (see [`files_for_template`]).
/// [`TemplateKind::Binary`] is the default and matches the original v0.1
/// `buff new` behavior (a runnable `src/main.buff`).
///
/// The `Server` and `Gpu` templates produce *starter* Buff source files that
/// demonstrate the intended async / GPU-dispatch syntax. Running them
/// end-to-end depends on the v1.0 runtime (`tokio` + `wgpu`), so in v0.5 the
/// file is created with reasonable starter content but `buff run` on it is
/// not yet expected to link.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum TemplateKind {
    /// A runnable application with `src/main.buff` (default; v0.1 behavior).
    #[default]
    Binary,
    /// A library module with `src/lib.buff` exporting functions for import.
    Lib,
    /// An async server starter (`async func` + `spawn`); v1.0 runtime to run.
    Server,
    /// A GPU-dispatch starter carrying `@prefer(gpu)` hints; v1.0 runtime to run.
    Gpu,
    /// A multi-crate workspace layout with member directories under `crates/`.
    Workspace,
}

impl TemplateKind {
    /// Lowercase kebab-name used in user-facing messages and (potentially)
    /// `--template <name>` options. Kept here so the CLI and any future
    /// `--template` value parser share a single source of truth.
    pub fn as_kebab(&self) -> &'static str {
        match self {
            TemplateKind::Binary => "binary",
            TemplateKind::Lib => "lib",
            TemplateKind::Server => "server",
            TemplateKind::Gpu => "gpu",
            TemplateKind::Workspace => "workspace",
        }
    }
}

/// Selects a [`TemplateKind`] from individual CLI boolean flags (T112).
///
/// Maps the `--lib` / `--server` / `--gpu` / `--workspace` flags from the
/// `New` clap variant onto a single [`TemplateKind`]. At most one flag may be
/// `true`; if all are `false`, returns [`TemplateKind::Binary`] (the default
/// — preserves the v0.1 `buff new NAME` behavior with no regressions).
///
/// # Errors
///
/// Returns a human-readable `String` if more than one flag is set.
pub fn template_from_flags(
    lib: bool,
    server: bool,
    gpu: bool,
    workspace: bool,
) -> Result<TemplateKind, String> {
    let set = [lib, server, gpu, workspace].iter().filter(|&&b| b).count();
    if set > 1 {
        return Err(
            "at most one template flag may be set (--lib, --server, --gpu, --workspace)"
                .to_string(),
        );
    }
    Ok(match (lib, server, gpu, workspace) {
        (true, _, _, _) => TemplateKind::Lib,
        (_, true, _, _) => TemplateKind::Server,
        (_, _, true, _) => TemplateKind::Gpu,
        (_, _, _, true) => TemplateKind::Workspace,
        _ => TemplateKind::Binary,
    })
}

